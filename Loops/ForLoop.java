//Loops are use to repeat the things 
//Types of loops are 
//1 For Loop 
//2 While Loop
//3 Do while Loop (execute atleast one)
public class ForLoop
{
    public static void main(String[] args)
    {
        int n = 10;
        for(int i=0;i<=n;i++)
        {
            System.out.println("Hello " + i);
        }
    }
}